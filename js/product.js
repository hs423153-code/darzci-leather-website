// RENDER PRODUCTS
// ===============================

function renderProducts() {

  const backpackGrid = document.getElementById("backpackGrid");
  const duffelGrid = document.getElementById("duffelGrid");
  const laptopbagsGrid = document.getElementById("laptopbagsGrid");
  const trolleyGrid = document.getElementById("trolleyGrid");
  const handbagsGrid = document.getElementById("handbagsGrid");
  const beltsGrid = document.getElementById("beltsGrid");

  if(backpackGrid){
    backpackGrid.innerHTML = "";
  }

  if(duffelGrid){
    duffelGrid.innerHTML = "";
  }

  if(laptopbagsGrid){
    laptopbagsGrid.innerHTML = "";
  }

  if(trolleyGrid){
    trolleyGrid.innerHTML = "";
  }

  if(handbagsGrid){
    handbagsGrid.innerHTML = "";
  }

  if(beltsGrid){
    beltsGrid.innerHTML = "";
  }

  products.forEach(product => {

    if(
    selectedCategory !== "all" &&
    product.category.toLowerCase() !== selectedCategory.toLowerCase()
){
    return;
}

    const card = createCard(product);

    

    if(product.category === "backpack"){
      backpackGrid.innerHTML += card;
    }

    if(product.category === "duffel"){
      duffelGrid.innerHTML += card;
    }

    if(product.category === "laptopbags"){
      laptopbagsGrid.innerHTML += card;
    }

    if(product.category === "trolley"){
      trolleyGrid.innerHTML += card;
    }

    if(product.category === "handbags"){
      handbagsGrid.innerHTML += card;
    }

    if(product.category === "belts"){
      beltsGrid.innerHTML += card;
    }

  });

}

renderProducts();

document.querySelectorAll(".category-section")
.forEach(section => {

    const grid =
    section.querySelector(".product-grid");

    if(grid && grid.children.length === 0){
        section.style.display = "none";
    }
    else{
        section.style.display = "block";
    }

});


// AUTOMATIC JS
function createCard(product){

return `

<div class="product-card">

${product.bestseller ?

'<span class="bestseller-badge">BESTSELLER</span>'

: ''}

<img src="${product.image}">

<h3>${product.name}</h3>

<div class="product-rating">

<span class="stars">
${generateStars(product.rating)}
</span>

<span class="review-count">
(${product.reviews})
</span>

</div>

<p class="price">
${product.price}
</p>

<a href="${product.link}"
class="btn">

View

</a>

</div>

`;

}

// STARS
function generateStars(rating){

let stars = "";

for(let i=1;i<=5;i++){

if(i<=Math.floor(rating)){
stars += "★";
}
else{
stars += "☆";
}

}

return stars;

}

// COMPLETE HAMBURGER MENU

const mobileToggle = document.getElementById("mobileToggle");
const mainNav = document.getElementById("mainNav");
const menuBackdrop = document.getElementById("menuBackdrop");

if (mobileToggle && mainNav) {

    mobileToggle.addEventListener("click", () => {

        mainNav.classList.toggle("active");

        if (menuBackdrop) {
            menuBackdrop.classList.toggle("active");
        }

        document.body.classList.toggle("menu-open");

        mobileToggle.innerHTML = mainNav.classList.contains("active")
            ? "✕"
            : "☰";

    });

}

if (menuBackdrop && mainNav && mobileToggle) {

    menuBackdrop.addEventListener("click", () => {

        mainNav.classList.remove("active");

        menuBackdrop.classList.remove("active");

        document.body.classList.remove("menu-open");

        mobileToggle.innerHTML = "☰";

    });

}

// CART COUNT
function updateCartCount() {

    const cart = JSON.parse(localStorage.getItem("cart")) || [];

    const cartCount = document.getElementById("cartCount");

    if (cartCount) {
        cartCount.textContent = cart.length;
    }

}

updateCartCount();



